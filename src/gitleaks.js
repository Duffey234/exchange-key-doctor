'use strict';
// Generates rules/gitleaks.toml from src/rules.js so both stay in sync.
const { RULES, STOPWORDS } = require('./rules');
const { link } = require('./links');

const tomlStr = (s) => `'''${s}'''`;

function render() {
  const out = [
    '# exchange-key-doctor: gitleaks rules for crypto exchange API credentials',
    '# (Binance, Bybit, OKX, Bitget). gitleaks\' default config has no rules for these.',
    '# Use: add to your .gitleaks.toml with  [extend] useDefault = true  and paste these rules,',
    '# or run:  gitleaks detect --config node_modules/exchange-key-doctor/rules/gitleaks.toml',
    `# What to do if one fires: ${link('leakTracker')}`,
    '# Generated by src/gitleaks.js; do not edit by hand.',
    '',
    'title = "exchange-key-doctor"',
    '',
    '[extend]',
    'useDefault = true',
    '',
  ];
  for (const r of RULES) {
    out.push('[[rules]]');
    out.push(`id = "${r.id}"`);
    out.push(`description = "${r.title}"`);
    out.push(`regex = ${tomlStr(r.gitleaks.regex)}`);
    out.push('secretGroup = 1');
    out.push(`entropy = ${r.gitleaks.entropy.toFixed(1)}`);
    out.push(`keywords = [${r.gitleaks.keywords.map((k) => `"${k}"`).join(', ')}]`);
    out.push('[[rules.allowlists]]');
    out.push(`stopwords = [${STOPWORDS.map((k) => `"${k}"`).join(', ')}]`);
    out.push('');
  }
  return out.join('\n');
}

module.exports = { render };
if (require.main === module) process.stdout.write(render());
